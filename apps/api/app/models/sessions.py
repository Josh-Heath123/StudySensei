"""Study sessions, their event log and the end-of-session reflection.

``session_events`` is the source of truth. The totals and state on
``study_sessions`` are a cache rebuilt from the events on every write
(see ``app/services/sessions/timeline.py``).

Reflections (focus rating, what was covered, confidence per topic) are personal
data: they must never be put in an AI prompt (decision 0002).

Isolation follows ``app/models/academics.py``: composite FKs that include
user_id or module_id, so Postgres rejects any cross-user or cross-module link.
"""

import uuid
from datetime import datetime

from sqlalchemy import (
    BigInteger,
    CheckConstraint,
    DateTime,
    Double,
    ForeignKeyConstraint,
    Identity,
    Index,
    SmallInteger,
    String,
    Text,
    UniqueConstraint,
    func,
    text,
)
from sqlalchemy.orm import Mapped, mapped_column

from app.models.academics import _in
from app.models.base import Base, TimestampedBase
from app.services.sessions.timeline import EVENT_TYPES, STATES


class StudySession(TimestampedBase):
    __tablename__ = "study_sessions"
    __table_args__ = (
        ForeignKeyConstraint(
            ["module_id", "user_id"], ["modules.id", "modules.user_id"], ondelete="CASCADE"
        ),
        # Deleting the topic keeps the session (and its module) but forgets the topic.
        ForeignKeyConstraint(
            ["topic_id", "module_id"],
            ["topics.id", "topics.module_id"],
            ondelete="SET NULL (topic_id)",
        ),
        # The planned block it was started from (decision 0021); deleting the block keeps
        # the session.
        ForeignKeyConstraint(
            ["plan_block_id", "user_id"],
            ["plan_blocks.id", "plan_blocks.user_id"],
            name="fk_study_sessions_plan_block_id_user_id_plan_blocks",
            ondelete="SET NULL (plan_block_id)",
        ),
        UniqueConstraint("id", "user_id", name="uq_study_sessions_id_user"),
        UniqueConstraint("id", "module_id", name="uq_study_sessions_id_module"),
        CheckConstraint(_in("state", STATES), name="ck_study_sessions_state"),
        CheckConstraint(
            "(state = 'ended') = (ended_at IS NOT NULL)", name="ck_study_sessions_ended"
        ),
        CheckConstraint(
            "active_seconds >= 0 AND break_seconds >= 0", name="ck_study_sessions_totals"
        ),
        CheckConstraint(
            "focus_rating IS NULL OR focus_rating BETWEEN 1 AND 5", name="ck_study_sessions_focus"
        ),
        CheckConstraint(
            "reflected_at IS NULL OR state = 'ended'", name="ck_study_sessions_reflect_ended"
        ),
        # At most one open session per user.
        Index(
            "uq_study_sessions_one_active",
            "user_id",
            unique=True,
            postgresql_where=text("ended_at IS NULL"),
        ),
        Index("ix_study_sessions_module_started", "module_id", "started_at"),
    )

    user_id: Mapped[uuid.UUID]
    module_id: Mapped[uuid.UUID]
    topic_id: Mapped[uuid.UUID | None]
    plan_block_id: Mapped[uuid.UUID | None]
    state: Mapped[str] = mapped_column(String(10))
    started_at: Mapped[datetime] = mapped_column(DateTime(timezone=True))
    ended_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True))
    last_event_at: Mapped[datetime] = mapped_column(DateTime(timezone=True))
    active_seconds: Mapped[float] = mapped_column(Double)
    break_seconds: Mapped[float] = mapped_column(Double)
    focus_rating: Mapped[int | None] = mapped_column(SmallInteger)
    covered_notes: Mapped[str | None] = mapped_column(Text)
    reflected_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True))


class SessionEvent(Base):
    """One timer event. Append-only; ``id`` is generated by the client.

    The primary key is (user_id, id), so ids are only unique per user: one user
    reusing another's event id can't collide with (and so can't detect) it.
    """

    __tablename__ = "session_events"
    __table_args__ = (
        ForeignKeyConstraint(
            ["session_id", "user_id"],
            ["study_sessions.id", "study_sessions.user_id"],
            ondelete="CASCADE",
        ),
        CheckConstraint(_in("type", EVENT_TYPES), name="ck_session_events_type"),
        Index("ix_session_events_session_time", "session_id", "occurred_at", "seq"),
    )

    user_id: Mapped[uuid.UUID] = mapped_column(primary_key=True)
    id: Mapped[uuid.UUID] = mapped_column(primary_key=True)
    session_id: Mapped[uuid.UUID]
    type: Mapped[str] = mapped_column(String(12))
    occurred_at: Mapped[datetime] = mapped_column(DateTime(timezone=True))
    # Server receive order; breaks ties between equal timestamps.
    seq: Mapped[int] = mapped_column(BigInteger, Identity(always=True))
    created_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), server_default=func.now())

    __mapper_args__ = {"eager_defaults": True}  # noqa: RUF012 (fetch seq with RETURNING)


class SessionTopicRating(Base):
    """Confidence (1-5) in a topic covered by a session. Both sides share a module."""

    __tablename__ = "session_topic_ratings"
    __table_args__ = (
        ForeignKeyConstraint(
            ["session_id", "module_id"],
            ["study_sessions.id", "study_sessions.module_id"],
            ondelete="CASCADE",
        ),
        ForeignKeyConstraint(
            ["topic_id", "module_id"], ["topics.id", "topics.module_id"], ondelete="CASCADE"
        ),
        CheckConstraint("confidence BETWEEN 1 AND 5", name="ck_session_topic_ratings_confidence"),
        Index("ix_session_topic_ratings_topic", "topic_id"),
    )

    session_id: Mapped[uuid.UUID] = mapped_column(primary_key=True)
    topic_id: Mapped[uuid.UUID] = mapped_column(primary_key=True)
    module_id: Mapped[uuid.UUID]
    confidence: Mapped[int] = mapped_column(SmallInteger)
