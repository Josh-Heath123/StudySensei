"""Request and response schemas for study sessions.

The client sends events (with its own UUIDs and timestamps), never durations.
"""

import uuid
from datetime import datetime
from typing import Annotated, Literal, Self

from pydantic import AwareDatetime, BaseModel, ConfigDict, Field, model_validator

from app.schemas.academics import _Input
from app.services.sessions.timeline import EventType, State

# Every event type except start, which only comes from POST /sessions.
LaterEventType = Literal["pause", "resume", "break_start", "break_end", "end"]
Rating = Annotated[int, Field(ge=1, le=5)]


class StartEvent(_Input):
    # Generated by the client; resending the same id returns the same session.
    id: uuid.UUID
    occurred_at: AwareDatetime


class EventIn(_Input):
    id: uuid.UUID
    type: LaterEventType
    occurred_at: AwareDatetime


class SessionStart(_Input):
    module_id: uuid.UUID
    topic_id: uuid.UUID | None = None
    start: StartEvent


class EventBatch(_Input):
    """Events to add, in any order. Ids already stored are skipped if unchanged."""

    events: list[EventIn] = Field(min_length=1, max_length=100)


class TopicRatingIn(_Input):
    topic_id: uuid.UUID
    confidence: Rating


class ReflectionIn(_Input):
    focus_rating: Rating
    covered_notes: str | None = Field(default=None, max_length=5000)
    # Confidence per topic covered; all in the session's module.
    topic_ratings: list[TopicRatingIn] = Field(default_factory=list, max_length=100)

    @model_validator(mode="after")
    def _topics_once_each(self) -> Self:
        ids = [rating.topic_id for rating in self.topic_ratings]
        if len(ids) != len(set(ids)):
            raise ValueError("Rate each topic at most once")
        return self


# --- Responses -----------------------------------------------------------------------


class EventOut(BaseModel):
    model_config = ConfigDict(from_attributes=True)

    id: uuid.UUID
    type: EventType
    occurred_at: datetime


class TopicRatingOut(BaseModel):
    model_config = ConfigDict(from_attributes=True)

    topic_id: uuid.UUID
    confidence: int


class SessionFields(BaseModel):
    model_config = ConfigDict(from_attributes=True)

    id: uuid.UUID
    module_id: uuid.UUID
    topic_id: uuid.UUID | None
    plan_block_id: uuid.UUID | None
    state: State
    started_at: datetime
    ended_at: datetime | None
    # Totals run up to last_event_at (measured from the events). While the state is
    # active or on_break, add (now - last_event_at) on the client's clock.
    last_event_at: datetime
    active_seconds: float
    break_seconds: float
    focus_rating: int | None
    covered_notes: str | None
    reflected_at: datetime | None
    created_at: datetime
    updated_at: datetime


class SessionOut(SessionFields):
    topic_ratings: list[TopicRatingOut]


class SessionDetailOut(SessionOut):
    """A session with its events in timeline order, for resuming the timer."""

    events: list[EventOut]
