// Writes THIRD_PARTY_NOTICES.md: `npm run licenses`. CI's hygiene job regenerates it and fails
// if the committed file differs, so keep it current after any dependency change.
//
// Lists every production dependency (Python from uv.lock, npm from package-lock.json) with its
// version and licence, from the same data as the CI licence check (scripts/license-data.mjs),
// plus the embedding model and the fonts, whose licences were checked by hand (below).
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";

import { npmProductionPackages, pythonProductionPackages, root } from "./license-data.mjs";

const allow = JSON.parse(readFileSync(path.join(root, "scripts/license-allowlist.json"), "utf8"));

// Checked on 18 Nov 2026 at the sources named. Re-check when the model or a font changes.
const MODEL = {
  name: "BAAI/bge-small-en-v1.5",
  license: "MIT",
  use: "Local text embeddings for search and topic links (apps/api/app/services/search/embedding.py).",
  source:
    "Licence on the model card at https://huggingface.co/BAAI/bge-small-en-v1.5. fastembed downloads " +
    "the ONNX copy Qdrant/bge-small-en-v1.5-onnx-Q (https://huggingface.co/Qdrant/bge-small-en-v1.5-onnx-Q), " +
    "also MIT. The model is downloaded at runtime to data/models and is not in the repository.",
};
const FONTS = [
  {
    name: "Inter",
    package: "@fontsource-variable/inter",
    license: "SIL Open Font License 1.1 (OFL-1.1)",
    copyright: "Copyright 2016 The Inter Project Authors (https://github.com/rsms/inter)",
  },
];

const cell = (text) => (text || "unknown").replace(/\|/g, "\\|");

function table(packages, notes = {}) {
  const rows = packages.map((pkg) => {
    const note = notes[pkg.name.toLowerCase().replace(/[-_.]+/g, "-")] ?? notes[pkg.name];
    const license = note ? `${cell(pkg.license)} (see note)` : cell(pkg.license);
    return `| ${cell(pkg.name)} | ${cell(pkg.version)} | ${license} |`;
  });
  return ["| Package | Version | Licence |", "| --- | --- | --- |", ...rows].join("\n");
}

const python = await pythonProductionPackages();
const npm = npmProductionPackages();
const pythonNotes = Object.fromEntries(
  Object.entries(allow.python ?? {}).map(([name, reason]) => [
    name.toLowerCase().replace(/[-_.]+/g, "-"),
    reason,
  ]),
);
const notes = Object.entries(pythonNotes)
  .filter(([name]) => python.some((pkg) => pkg.name.toLowerCase().replace(/[-_.]+/g, "-") === name))
  .map(([name, reason]) => `- **${name}:** ${reason}`);

const text = `# Third-party notices

<!-- Generated by \`npm run licenses\` (scripts/third-party-notices.mjs). Don't edit by hand: CI fails if this file is stale. -->

StudySensei is proprietary (see [LICENSE](LICENSE)). It uses the third-party components below, each under its own
licence. The lists are StudySensei's production dependencies: Python packages from \`apps/api/uv.lock\` (dev tools
left out) and npm packages from \`package-lock.json\` (including platform-specific builds). Licences are as each
package declares them.

## Embedding model

- **${MODEL.name}**: ${MODEL.license}. ${MODEL.use}
  ${MODEL.source}

## Font

Self-hosted from npm (no requests to Google Fonts).

${FONTS.map((font) => `- **${font.name}** (\`${font.package}\`): ${font.license}. ${font.copyright}.`).join("\n")}

## Python packages (${python.length})

${table(python, pythonNotes)}
${notes.length ? `\nNotes:\n\n${notes.join("\n")}\n` : ""}
## npm packages (${npm.length})

${table(npm)}
`;

writeFileSync(path.join(root, "THIRD_PARTY_NOTICES.md"), text, { encoding: "utf8" });
console.log(`Wrote THIRD_PARTY_NOTICES.md: ${python.length} Python and ${npm.length} npm packages`);
